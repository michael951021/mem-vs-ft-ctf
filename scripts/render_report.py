"""Render the data-derived sections of REPORT.md from logged results ONLY.

Produces results/RESULTS_AUTO.md: the success tables, H1/H2 numbers, efficiency,
and a per-arm run_id index. Every value comes from results/summary.json (written
by scripts.analyze) and the run dirs; where an arm/split has n=0 it prints
"not yet measured (pending <queued job>)" rather than any placeholder number.

REPORT.md's <!--RESULTS_AUTO--> marker is replaced with this block by
`--inject`, so the final report never contains a hand-typed result.

Usage:
  python -m scripts.analyze                      # refresh summary.json first
  python -m scripts.render_report --inject       # write RESULTS_AUTO.md + patch REPORT.md
"""
from __future__ import annotations

import argparse
import glob
import json
import os

SPLITS = ["train", "test-indist", "test-transfer"]
ARMNAME = {"A": "A no-memory", "B": "B raw-ICL", "C": "C episodic-retrieval",
           "D": "D ACE-playbook", "E": "E QLoRA weights", "F": "F hybrid"}


def run_index():
    """Map arm -> [run_ids], reading the arm from each run's config snapshot."""
    idx = {}
    for cfg in glob.glob("runs/*/config.yaml") + glob.glob("runs/*/config.json"):
        rid = os.path.basename(os.path.dirname(cfg))
        arm = "?"
        try:
            if cfg.endswith(".json"):
                with open(cfg) as f:
                    arm = json.load(f).get("arm", "?")
            else:
                import yaml
                with open(cfg) as f:
                    arm = yaml.safe_load(f).get("arm", "?")
        except Exception:
            parts = rid.split("-")
            arm = parts[2] if len(parts) > 2 else "?"
        idx.setdefault(str(arm), []).append(rid)
    return idx


def md_table(summary):
    arms = summary["arms"]
    lines = ["| arm | " + " | ".join(SPLITS) + " |",
             "|---|" + "---|" * len(SPLITS)]
    for a in arms:
        cells = []
        for s in SPLITS:
            key = f"{a}|{s}"
            e = summary["success_rate"].get(key, {"rate": 0, "n": 0})
            cells.append(f"{e['rate']:.2f} (n={e['n']})" if e["n"] else "—")
        lines.append(f"| {ARMNAME.get(a, a)} | " + " | ".join(cells) + " |")
    return "\n".join(lines)


def render(summary):
    out = []
    out.append("<!-- AUTO-GENERATED by scripts/render_report.py from results/summary.json. "
               "Do not edit by hand. -->")
    out.append(f"\n**Data as logged:** {summary['n_attempts']} attempts, "
               f"arms {summary['arms']}, seeds {summary['seeds']}.\n")
    out.append("#### Success rate by arm and split\n")
    out.append(md_table(summary))

    out.append("\n#### H1 — in-distribution advantage over Arm A (paired, clustered bootstrap 95% CI)\n")
    h1 = summary.get("H1_advantage_over_A", {})
    if h1:
        out.append("| arm | Δ vs A | 95% CI | clusters |")
        out.append("|---|---|---|---|")
        for a, adv in h1.items():
            out.append(f"| {ARMNAME.get(a, a)} | {adv['advantage']:+.3f} | "
                       f"[{adv['ci_lo']:+.3f}, {adv['ci_hi']:+.3f}] | {adv['n_clusters']} |")
    else:
        out.append("_Not yet measured (needs >=2 arms with test-indist rows; "
                   "pending the pilot's memory arms)._")

    out.append("\n#### H1b — step-efficiency: turns saved vs Arm A on jointly-solved tasks\n")
    out.append("_The informative metric when success is at ceiling: a verified "
               "recipe in memory should let the agent solve in fewer turns._\n")
    h1b = summary.get("H1b_turns_saved_vs_A", {})
    rows_b = [(k, v) for k, v in h1b.items() if v.get("n_pairs")]
    if rows_b:
        out.append("| arm·split | turns saved vs A | 95% CI | pairs |")
        out.append("|---|---|---|---|")
        for k, v in rows_b:
            out.append(f"| {k} | {v['turns_saved_vs_A']:+.2f} | "
                       f"[{v['ci_lo']:+.2f}, {v['ci_hi']:+.2f}] | {v['n_pairs']} |")
    else:
        out.append("_Not yet measured (needs a memory arm and Arm A to both solve "
                   "the same tasks)._")

    out.append("\n#### H2 — transfer retention to sibling surfaces\n")
    h2 = summary.get("H2_transfer_retention", {})
    if any(v.get("retention") is not None for v in h2.values()):
        out.append("| arm | adv in-dist | adv transfer | retention |")
        out.append("|---|---|---|---|")
        for a, tr in h2.items():
            r = tr["retention"]
            out.append(f"| {ARMNAME.get(a, a)} | {tr['adv_indist']:+.3f} | "
                       f"{tr['adv_transfer']:+.3f} | {r if r is not None else '—'} |")
    else:
        out.append("_Not yet measured (needs a non-zero in-distribution advantage "
                   "to normalise against)._")

    out.append("\n#### Efficiency (on solved tasks)\n")
    eff = summary.get("efficiency", {})
    if eff:
        out.append("| arm·split | mean turns | mean out-tokens | n solves |")
        out.append("|---|---|---|---|")
        for k, e in eff.items():
            out.append(f"| {k} | {e['mean_turns_to_solve']} | {e['mean_out_tokens']} | {e['n_solves']} |")

    out.append("\n#### Run index (traceability)\n")
    idx = run_index()
    for arm, rids in sorted(idx.items()):
        out.append(f"- **arm {arm}**: " + ", ".join(f"`{r}`" for r in sorted(rids)))
    return "\n".join(out) + "\n"


def render_hard(summary):
    """Compact hard-tier (chained-mechanism) block: success + step-efficiency."""
    out = ["\n### 5.2 Hard tier (crypto/chain: decode→XOR, sibling surfaces)\n",
           f"_{summary['n_attempts']} attempts, arms {summary['arms']}, "
           f"seeds {summary['seeds']}._\n"]
    out.append(md_table(summary))
    h1b = {k: v for k, v in summary.get("H1b_turns_saved_vs_A", {}).items()
           if v.get("n_pairs")}
    out.append("\n**Step-efficiency (turns saved vs Arm A, jointly-solved):**")
    if h1b:
        out.append("\n| arm·split | turns saved vs A | 95% CI | pairs |")
        out.append("|---|---|---|---|")
        for k, v in h1b.items():
            out.append(f"| {k} | {v['turns_saved_vs_A']:+.2f} | "
                       f"[{v['ci_lo']:+.2f}, {v['ci_hi']:+.2f}] | {v['n_pairs']} |")
    else:
        out.append(" _pending the hard-tier memory arms._")
    return "\n".join(out) + "\n"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--summary", default="results/summary.json")
    ap.add_argument("--inject", action="store_true")
    args = ap.parse_args()
    if not os.path.isfile(args.summary):
        print("no summary.json; run scripts.analyze first"); return
    with open(args.summary) as f:
        summary = json.load(f)
    block = render(summary)
    if os.path.isfile("results/summary_hard.json"):
        with open("results/summary_hard.json") as f:
            block += render_hard(json.load(f))
    os.makedirs("results", exist_ok=True)
    with open("results/RESULTS_AUTO.md", "w") as f:
        f.write(block)
    print("wrote results/RESULTS_AUTO.md")
    if args.inject and os.path.isfile("REPORT.md"):
        with open("REPORT.md") as f:
            rep = f.read()
        start, end = "<!--RESULTS_AUTO-->", "<!--/RESULTS_AUTO-->"
        if start in rep and end in rep:
            pre = rep.split(start)[0]
            post = rep.split(end)[1]
            rep = pre + start + "\n" + block + end + post
            with open("REPORT.md", "w") as f:
                f.write(rep)
            print("injected results into REPORT.md")
        else:
            print("REPORT.md has no <!--RESULTS_AUTO--> markers; skipped inject")


if __name__ == "__main__":
    main()
